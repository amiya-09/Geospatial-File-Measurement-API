"""Write docs/accuracy.md: measurement error versus pyproj.Geod for boxes of growing size.

Run from the repo root: python scripts/make_accuracy_doc.py
"""

from pathlib import Path

import shapely
from pyproj import Geod
from shapely.geometry import LineString, box

from app.geo.measure import measure

GEOD = Geod(ellps="WGS84")
SIZES = (0.1, 1, 5, 10, 20)
LATITUDES = (0, 45, 70)
OUT = Path(__file__).resolve().parent.parent / "docs" / "accuracy.md"

INTRO = """\
# Accuracy against pyproj.Geod

This file is generated by `scripts/make_accuracy_doc.py`. Do not edit it by hand.

Each row is a box centred on longitude 0 and the stated latitude, with the stated width and
height in degrees. Every error is ours divided by Geod, minus 1, in percent. Ours is the API's own
pipeline (`app.geo.measure.measure`): a local equal-area projection for area and a local
equidistant projection for length, both centred on the shape. Geod measures on the WGS84
ellipsoid and shares no steps with that method.

Four columns:

- Area, corner edges: Geod joins the four corners with geodesics. Our projected polygon also
  joins the corners with straight lines, but straight in a different map, so the two
  disagree on what the edge is.
- Area, lon/lat edges: the box edges are cut every 0.01 degrees first, so both sides follow
  the meridians and parallels. This isolates the projection distortion.
- Diagonal length: a two point line from the south west to the north east corner. Geod gives
  the true geodesic distance.
- East west length: a two point line along the centre latitude, west edge to east edge.

"""

OUTRO = """
How to read this: for a box of 1 degree or less every column is under 0.004 percent. The
gap in the corner edges column for big boxes is mostly an edge interpretation difference (the
two methods draw different edges between the same corners), not projection error: the lon/lat
edges column stays small for the same boxes. The values are pinned for the 10 degree box in
`tests/test_accuracy_large_box.py`.
"""


def pct(ours: float, ref: float) -> str:
    return f"{(ours / ref - 1) * 100:+.4f}"


def geod_area(poly) -> float:
    return abs(GEOD.geometry_area_perimeter(poly)[0])


def row(size: float, lat: float) -> str:
    h = size / 2
    poly = box(-h, lat - h, h, lat + h)
    ours_area = measure(poly).area_m2
    dense = shapely.segmentize(poly, 0.01)
    ours_dense = measure(dense).area_m2

    diag = LineString([(-h, lat - h), (h, lat + h)])
    ew = LineString([(-h, lat), (h, lat)])
    diag_ref = GEOD.line_length(*zip(*diag.coords, strict=True))
    ew_ref = GEOD.line_length(*zip(*ew.coords, strict=True))
    return (
        f"| {size:g} | {lat} | {pct(ours_area, geod_area(poly))} "
        f"| {pct(ours_dense, geod_area(dense))} "
        f"| {pct(measure(diag).length_m, diag_ref)} "
        f"| {pct(measure(ew).length_m, ew_ref)} |"
    )


def main() -> None:
    lines = [
        "| Box size (deg) | Latitude | Area, corner edges (%) | Area, lon/lat edges (%) "
        "| Diagonal length (%) | East west length (%) |",
        "|---|---|---|---|---|---|",
    ]
    lines += [row(s, lat) for s in SIZES for lat in LATITUDES]
    OUT.write_text(INTRO + "\n".join(lines) + "\n" + OUTRO)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
